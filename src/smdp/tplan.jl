기본값이 남아 있어서가 아니라 적합 결과가 `1.0` 이기 때문이다.** 이 두 문장을 혼동하면
"T10 이 이 자리를 안 채웠다" 고 읽게 된다 — 채웠고, 데이터가 `1.0` 을 냈다.

**적합의 전부**(`tools/monitor/fit_rho.jl`, 산출물 `results/smdp/rho.json`):

