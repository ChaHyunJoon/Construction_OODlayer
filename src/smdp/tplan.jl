`T_plan_next`/`T_done` 이 ρ 에 대해 **정확히 선형**이므로(시험이 못박는다) 이 `Ref` 하나만
바꾸면 두 함수가 같이 움직인다 — 후속 태스크가 혼잡도 의존 ρ 로 갈 때 그 자리가 여기다.
