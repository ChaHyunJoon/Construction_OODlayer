🔴 **`dt_sim = 0.025 s` 눈금이 이 적합을 지배한다.** 실측: 계획 소요시간 **150/150 이 전부
`dt_sim` 격자 위에 있고**(분모도 격자다), 실현 소요시간은 정의상 격자다. 그래서 비는 유리수
격자에 갇히고 `1.0` 근방에 큰 원자가 생긴다. 부분모집단으로 나눠 재면:

